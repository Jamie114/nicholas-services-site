// Run: npm run test:duty. Reference values are from the state revenue offices.
import { buildSync } from 'esbuild';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const temporary = mkdtempSync(join(tmpdir(), 'duty-test-'));
try {
  for (const file of ['duty', 'calculations']) buildSync({entryPoints:[`src/${file}.ts`], outfile:join(temporary,`${file}.cjs`), bundle:true, platform:'node', format:'cjs'});
  const require = createRequire(import.meta.url);
  const { residentialDuty, schemePriceCap } = require(join(temporary,'duty.cjs'));
  const { calcOneProperty, calcTwoProperties, DEFAULTS } = require(join(temporary,'calculations.cjs'));
  function eq(actual, expected, label) { assert.ok(Math.abs(actual-expected)<0.02, `${label}: expected ${expected}, got ${actual}`); }
  const duty=(v,s,owner=true,first=true,kind='Established')=>residentialDuty(v,s,owner,first,kind);
  eq(duty(600000,'VIC'),0,'VIC threshold');
  eq(duty(700000,'VIC'),24713.333333333,'VIC concession');
  eq(duty(1000000,'VIC',false,false),55000,'VIC general');
  eq(duty(800000,'NSW'),0,'NSW exemption');
  eq(duty(850000,'NSW'),9796.75,'NSW published reduced example');
  eq(duty(900000,'NSW'),19593.5,'NSW published reduced example');
  eq(duty(1350000,'NSW',false,false),55537,'NSW published general example');
  eq(duty(650000,'QLD'),0,'QLD first-home example');
  eq(duty(730000,'QLD'),6555,'QLD first-home example');
  eq(duty(850000,'QLD'),24100,'QLD home concession example');
  eq(duty(850000,'QLD',false,false),31275,'QLD general example');
  eq(duty(1500000,'QLD',true,true,'New'),0,'QLD new home first buyer');
  eq(duty(600000,'WA'),0,'WA exemption');
  eq(duty(700000,'WA'),16150,'WA concession');
  eq(duty(700000,'SA',true,true,'New'),0,'SA new home');
  eq(duty(700000,'SA'),32330,'SA established home');
  eq(duty(800000,'TAS'),31185,'TAS general duty');
  eq(duty(900000,'ACT',true,false),28058,'ACT owner occupier');
  eq(duty(900000,'ACT',false,false),31050,'ACT non-owner occupier');
  eq(duty(1500000,'ACT'),0,'ACT eligible concession');
  eq(duty(700000,'NT'),34650,'NT general');
  eq(schemePriceCap('VIC','Capital / eligible regional centre'),950000,'Victoria scheme cap');
  eq(schemePriceCap('VIC','Other areas'),650000,'regional Victoria scheme cap');
  const base={...DEFAULTS.oneProperty,purchaseType:'FHOG',state:'VIC',homeKind:'Established',housePrice:'700000',desiredLvr:'95',interestRate:'5.9',loanTerm:'30'};
  const calc=x=>calcOneProperty({...base,...x}).outputs;
  assert.notEqual(calc({})['LMI Costs'],'$0','LMI is not automatically waived for first home buyer');
  assert.equal(calc({lmiExempt:true,lmiBasis:'5% Deposit Scheme',schemeArea:''})['LMI Costs'],'$31,920','scheme does not guess area');
  assert.equal(calc({lmiExempt:true,lmiBasis:'5% Deposit Scheme',schemeArea:'Capital / eligible regional centre'})['LMI Costs'],'$0','scheme within cap');
  assert.notEqual(calc({lmiExempt:true,lmiBasis:'5% Deposit Scheme',schemeArea:'Other areas'})['LMI Costs'],'$0','scheme over selected area cap');
  assert.equal(calc({lmiExempt:true,lmiBasis:'Lender / professional waiver',exemptCap:'95'})['LMI Costs'],'$0','manual LMI waiver');
  const professional={lmiExempt:true,lmiBasis:'Lender / professional waiver',exemptCap:'90'};
  assert.equal(calc(professional)['Requested LVR'],'95.00%','desired LVR remains visible');
  assert.equal(calc(professional)['Applied / Capped LVR'],'90.00%','professional waiver caps applied LVR');
  assert.equal(calc(professional)['Base Loan-to-Value Ratio'],'90.00%','loan respects waiver cap');
  assert.equal(calc(professional)['LMI Costs'],'$0','eligible professional waiver remains free of LMI at the boundary');
  assert.equal(calc({...professional,desiredLvr:'85'})['Applied / Capped LVR'],'85.00%','lower desired LVR is unchanged');
  assert.equal(calc({...professional,lmiExempt:false})['Applied / Capped LVR'],'95.00%','unchecking waiver restores desired LVR');
  assert.notEqual(calc({...professional,lmiExempt:false})['LMI Costs'],'$0','unchecking waiver calculates LMI');
  assert.equal(calc({...professional,exemptCap:'0'})['Maximum Purchase Price'],'$700,000');
  assert.equal(calcOneProperty({...base,...professional,exemptCap:'0'}).isComplete,false,'invalid waiver cap pauses results');
  assert.equal(calcOneProperty({...base,...professional,exemptCap:''}).isComplete,false,'blank waiver cap pauses results');
  assert.equal(calcOneProperty({...base,...professional,exemptCap:'101'}).isComplete,false,'cap above 100 pauses results');
  const example=calc({...professional,maxPurchaseMode:true,maxCashContribution:'60000',loanApprovalMax:'750000'});
  assert.equal(example['Maximum Purchase Price'],'$580,000','cash and waiver cap limit maximum price');
  assert.equal(example['Final Loan'],'$522,000','loan uses the 90% cap');
  assert.equal(example['LMI Costs'],'$0','no LMI in capped maximum-price example');
  assert.equal(calc({...professional,lmiBasis:'5% Deposit Scheme',schemeArea:'Capital / eligible regional centre'})['Applied / Capped LVR'],'95.00%','professional cap does not override scheme');
  assert.equal(calc({})['Stamp Duty'],'$24,713','first-home duty relief automatically applied');
  assert.notEqual(calc({firstHomeReliefOptOut:true})['Stamp Duty'],'$24,713','ineligible buyer can switch relief off');
  assert.equal(calc({firstHomeEligible:false})['Stamp Duty'],'$24,713','old saved cases use automatic relief');
  assert.equal(calc({maxPurchaseMode:true,loanApprovalMax:'',maxCashContribution:''})['Maximum Purchase Price'],'-','maximum mode does not use a hidden property price');
  assert.equal(calc({maxPurchaseMode:true,loanApprovalMax:'',maxCashContribution:'',desiredLvr:''})['Maximum Purchase Price'],'-','maximum mode requires LVR');
  assert.equal(calc({maxPurchaseMode:true,loanApprovalMax:'665000',maxCashContribution:''})['Maximum Purchase Price'],'$700,000','maximum from approval and LVR');
  const legacy={...base}; delete legacy.state; delete legacy.homeKind; delete legacy.firstHomeEligible;
  assert.equal(calcOneProperty(legacy).outputs['State / territory'],'VIC','legacy saved cases default to Victoria');
  const second=calcTwoProperties({...DEFAULTS.twoProperties,state:'NSW',currentValue:'800000',currentMortgage:'400000',secondPrice:'700000',desiredLvr:'80',loanTerm:'30'});
  assert.equal(second.outputs['New property state / territory'],'NSW');
  console.log('Duty, scheme caps, LMI and saved-case checks passed.');
} finally { rmSync(temporary,{recursive:true,force:true}); }
